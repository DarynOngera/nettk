/* IPv4/8.8 synthetic fragments: Ethernet + IPv4(proto UDP) + UDP + 4 bytes. */
static uint8_t frag_first[46] = {
    0x02, 0x00, 0x00, 0x00, 0x02, 0x02, 0x02, 0x00, 0x00, 0x00, 0x01, 0x02, 0x08, 0x00,
    0x45, 0x00, 0x00, 0x20, 0x00, 0x0a, 0x20, 0x00, 0x40, 0x11, 0x00, 0x00, 0x0a, 0x00,
    0x01, 0x02, 0x0a, 0x00, 0x02, 0x02, 0x00, 0x35, 0x00, 0x35, 0x00, 0x0c, 0x00, 0x00,
    'a', 'b', 'c', 'd',
};

int main(void)
{
    nt_packet p;

    /* ARP request from basic.pcap frame 1 (reconstructed header) */
    static const uint8_t f_arp[42] = {
        0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x02, 0x00, 0x00, 0x00, 0x01, 0x02, 0x08, 0x06,
        0x00, 0x01, 0x08, 0x00, 0x06, 0x04, 0x00, 0x01, 0x02, 0x00, 0x00, 0x00, 0x01, 0x02,
        0x0a, 0x00, 0x01, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x0a, 0x00, 0x01, 0x01,
    };
    NT_EQ_INT(nt_decode_frame(f_arp, sizeof f_arp, &p), NT_OK);
    NT_CHECK(p.has_eth);
    NT_CHECK(p.has_arp);
    NT_EQ_INT(p.l3_off, 14);
    NT_EQ_INT(p.arp.op, 1);

    /* IPv4 + ICMP */
    NT_EQ_INT(nt_decode_frame(f_icmp, sizeof f_icmp, &p), NT_OK);
    NT_CHECK(p.has_ipv4);
    NT_CHECK(p.has_icmp);
    NT_CHECK(!p.has_tcp && !p.has_udp);
    NT_EQ_INT(p.l3_off, 14);
    NT_EQ_INT(p.l4_off, 34);
    NT_EQ_INT(p.ip4.proto, 1);
    NT_EQ_INT(p.icmp.type, 8);

    /* IPv4 + TCP with options */
    NT_EQ_INT(nt_decode_frame(f_tcp, sizeof f_tcp, &p), NT_OK);
    NT_CHECK(p.has_tcp);
    NT_EQ_INT(p.tcp.sport, 40000);
    NT_EQ_INT(p.tcp.mss, 1460);
    NT_EQ_INT(p.tcp.csum_state, NT_CSUM_VALID);

    /* IPv4 + UDP */
    NT_EQ_INT(nt_decode_frame(f_udp, sizeof f_udp, &p), NT_OK);
    NT_CHECK(p.has_udp);
    NT_EQ_INT(p.udp.dport, 53);
    NT_EQ_INT(p.payload_len, 29);
    NT_EQ_INT(p.udp.csum_state, NT_CSUM_VALID);

    /* 802.1Q-tagged ICMP */
    NT_EQ_INT(nt_decode_frame(f_vlan_icmp, sizeof f_vlan_icmp, &p), NT_OK);
    NT_CHECK(p.has_vlan);
    NT_EQ_INT(p.vlan.tag[0].vid, 50);
    NT_EQ_INT(p.l3_off, 18);
    NT_CHECK(p.has_icmp);

    /* IPv4 fragment with offset 0: we decode the first L4 header (tshark does not) */
    NT_EQ_INT(nt_decode_frame(frag_first, sizeof frag_first, &p), NT_OK);
    NT_CHECK(p.has_ipv4);
    NT_CHECK(p.ip4.is_fragment);
    NT_CHECK(p.ip4.has_l4);
    NT_CHECK(p.has_udp);

    /* later fragment: stop at L3, no transport header */
    frag_first[20] = 0x00; frag_first[21] = 0x01; /* frag_off 1, MF clear */
    NT_EQ_INT(nt_decode_frame(frag_first, sizeof frag_first, &p), NT_OK);
    NT_CHECK(p.ip4.is_fragment);
    NT_CHECK(!p.ip4.has_l4);
    NT_CHECK(!p.has_udp);

    /* IPv6 + ICMPv6 echo */
    NT_EQ_INT(nt_decode_frame(f_v6_echo, sizeof f_v6_echo, &p), NT_OK);
    NT_CHECK(p.has_ipv6);
    NT_CHECK(p.has_icmpv6);
    NT_EQ_INT(p.l3_off, 14);
    NT_EQ_INT(p.l4_off, 54);
    NT_EQ_INT(p.ip6.next_hdr, 58);
    NT_EQ_INT(p.icmpv6.type, 128);

    /* IPv6 + NDP neighbour solicitation */
    NT_EQ_INT(nt_decode_frame(f_v6_ns, sizeof f_v6_ns, &p), NT_OK);
    NT_CHECK(p.has_icmpv6);
    NT_EQ_INT(p.icmpv6.type, 135);
    NT_EQ_INT(p.icmpv6.has_target, 1);
    const uint8_t ns_target[16] = {
        0xfd, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x02, 0x00, 0x02,
    };
    NT_EQ_MEM(p.icmpv6.target, ns_target, 16);

    /* truncated Ethernet frame */
    NT_EQ_INT(nt_decode_frame(f_icmp, 10, &p), NT_ERR_TRUNCATED);
    NT_CHECK(!p.has_eth);
    NT_EQ_INT(p.status, NT_ERR_TRUNCATED);

    /* IPv4 header truncated below the minimum */
    NT_EQ_INT(nt_decode_frame(f_icmp, 14 + 10, &p), NT_ERR_TRUNCATED);
    NT_CHECK(p.has_eth);
    NT_EQ_INT(p.status, NT_ERR_TRUNCATED);

    /* unsupported 802.3 length at offset 12 */
    static const uint8_t f_8023[14] = {
        0x02, 0x00, 0x00, 0x00, 0x02, 0x02, 0x02, 0x00, 0x00, 0x00, 0x01, 0x02, 0x00, 0x2a,
    };
    NT_EQ_INT(nt_decode_frame(f_8023, sizeof f_8023, &p), NT_ERR_UNSUPPORTED);
    NT_CHECK(p.has_eth);
    NT_EQ_INT(p.status, NT_ERR_UNSUPPORTED);

    NT_DONE();
}
